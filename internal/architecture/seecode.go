package architecture

import (
	"fmt"
	"strings"
)

// Spec is a SeeCode architecture spec (seecode references/types/architecture.md).
type Spec struct {
	Type     string         `json:"type"`
	Title    string         `json:"title"`
	Subtitle string         `json:"subtitle,omitempty"`
	Caption  string         `json:"caption,omitempty"`
	Dir      string         `json:"dir"`
	Nodes    []SpecNode     `json:"nodes"`
	Edges    []SpecEdge     `json:"edges"`
	Groups   []SpecGroup    `json:"groups,omitempty"`
	Legend   map[string]any `json:"legend,omitempty"`
	Evidence []SpecEvidence `json:"evidence,omitempty"`
}

// SpecNode is one SeeCode node.
type SpecNode struct {
	ID    string `json:"id"`
	Label string `json:"label"`
	Sub   string `json:"sub,omitempty"`
	Tag   string `json:"tag,omitempty"`
	Kind  string `json:"kind,omitempty"`
	Focal bool   `json:"focal,omitempty"`
	Row   int    `json:"row"`
	Col   int    `json:"col"`
	Group string `json:"group,omitempty"`
}

// SpecEdge is one SeeCode edge in object form.
type SpecEdge struct {
	From  string `json:"from"`
	To    string `json:"to"`
	Label string `json:"label,omitempty"`
	Kind  string `json:"kind,omitempty"`
	Both  bool   `json:"both,omitempty"`
}

// SpecGroup is one SeeCode group.
type SpecGroup struct {
	ID    string `json:"id"`
	Label string `json:"label"`
	Style string `json:"style,omitempty"`
}

// SpecEvidence links a node to a source file.
type SpecEvidence struct {
	ID   string `json:"id"`
	File string `json:"file"`
	Line int    `json:"line,omitempty"`
	Note string `json:"note,omitempty"`
}

// SeeCode's text limits (schemas/graph.schema.json, common.schema.json).
const (
	maxNodeLabel  = 40
	maxNodeSub    = 48
	maxEdgeLabel  = 28
	maxGroupLabel = 32
	maxSubtitle   = 160
	maxCaption    = 280
)

// SeeCode turns a diagram into a SeeCode architecture spec. Declared links
// are dashed ("async", "declared link" in the legend); declared placement
// groups are dashed and labelled "(declared)", inferred ones "(inferred)".
// Every node carries its top files as evidence. Text is clipped to SeeCode's
// limits.
func SeeCode(d *Diagram) Spec {
	s := Spec{Type: "architecture", Title: d.Title, Dir: "TB", Nodes: []SpecNode{}, Edges: []SpecEdge{}}
	commit := d.Commit
	if len(commit) > 7 {
		commit = commit[:7]
	}
	s.Subtitle = fmt.Sprintf("Generated by highstakes from %s@%s: %d of %d product units by impact", d.Repo, commit, countKind(d, KindUnit), d.ProductUnits)
	var caption []string
	caption = append(caption, "Solid arrows: imports (importing files). Dashed arrows and dashed groups: declared in .heatmap/architecture.yaml. Other groups: inferred from Dockerfiles, Helm values or manifests.")
	if d.DroppedEdges > 0 {
		caption = append(caption, fmt.Sprintf("%d more links not drawn (edge budget).", d.DroppedEdges))
	}
	if d.SupportingHidden > 0 {
		caption = append(caption, fmt.Sprintf("%d supporting unit(s) hidden.", d.SupportingHidden))
	}
	s.Caption = clip(strings.Join(caption, " "), maxCaption)
	s.Subtitle = clip(s.Subtitle, maxSubtitle)

	for _, n := range d.Nodes {
		sn := SpecNode{ID: n.ID, Label: clip(n.Label, maxNodeLabel), Sub: clip(n.Sub, maxNodeSub), Tag: n.Tag, Focal: n.Focal, Row: n.Row, Col: n.Col, Group: n.Group}
		if n.Kind == KindOther {
			sn.Kind = "muted"
		}
		s.Nodes = append(s.Nodes, sn)
		for _, f := range n.Files {
			s.Evidence = append(s.Evidence, SpecEvidence{ID: n.ID, File: f.Path, Line: f.Line, Note: f.Note})
		}
	}
	for _, e := range d.Edges {
		se := SpecEdge{From: e.From, To: e.To, Label: clip(e.Label, maxEdgeLabel), Both: e.Both}
		if e.Source == SourceDeclared {
			se.Kind = "async"
		}
		s.Edges = append(s.Edges, se)
	}
	for _, g := range d.Groups {
		suffix := " (" + g.Source + ")"
		sg := SpecGroup{ID: g.ID, Label: clip(g.Label, maxGroupLabel-len(suffix)) + suffix}
		if g.Source == SourceDeclared {
			sg.Style = "dashed"
		}
		s.Groups = append(s.Groups, sg)
	}
	s.Legend = map[string]any{"entries": map[string]any{
		"default": map[string]string{"label": "imports (files)"},
		"async":   map[string]string{"label": "declared (architecture.yaml)"},
	}}
	return s
}

func countKind(d *Diagram, kind string) int {
	n := 0
	for _, x := range d.Nodes {
		if x.Kind == kind {
			n++
		}
	}
	return n
}

// clip shortens s to at most n runes, ending in "…" when cut.
func clip(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return string(r[:n-1]) + "…"
}
