// Package policy turns a heatmap into review policy artifacts: hot path lists,
// a CODEOWNERS block, and a no-auto-approve policy for AI reviewers.
package policy

import (
	"fmt"
	"path"
	"sort"
	"strings"

	"github.com/zanetworker/highstakes/internal/ownership"
	"github.com/zanetworker/highstakes/internal/scorer"
	"github.com/zanetworker/highstakes/internal/types"
)

// Markers delimit the generated block inside CODEOWNERS.
const (
	BeginMarker = "# BEGIN highstakes (generated by `highstakes create codeowners --write`; edits inside are overwritten)"
	EndMarker   = "# END highstakes"
)

// Entry is a hot path: a single file, or a directory whose scored files are all hot.
type Entry struct {
	Path      string     `json:"path"` // "dir/" for directories
	IsDir     bool       `json:"is_dir"`
	Tier      types.Tier `json:"tier"`
	HeatScore int        `json:"heat_score"`
	Files     []string   `json:"files"`
}

var tierRank = map[types.Tier]int{types.TierLow: 0, types.TierMedium: 1, types.TierHigh: 2, types.TierCritical: 3}

// TierAtLeast reports whether t ranks at or above min.
func TierAtLeast(t, min types.Tier) bool { return tierRank[t] >= tierRank[min] }

// ParseTier validates a tier name.
func ParseTier(s string) (types.Tier, error) {
	t := types.Tier(strings.ToLower(strings.TrimSpace(s)))
	if _, ok := tierRank[t]; !ok {
		return "", fmt.Errorf("invalid tier %q. Valid values: critical, high, medium, low", s)
	}
	return t, nil
}

// IsHot reports whether a file belongs on a protected-path list for minTier:
// its tier is at least minTier, or its LLM-assessed impact is at least the
// threshold of minTier. The impact rule keeps stable, high-impact files on
// the list even when they rarely change.
func IsHot(f *types.FileHeat, minTier types.Tier, th types.TierThresholds) bool {
	if TierAtLeast(f.Tier, minTier) {
		return true
	}
	limit := map[types.Tier]int{types.TierCritical: th.Critical, types.TierHigh: th.High, types.TierMedium: th.Medium, types.TierLow: th.Low}[minTier]
	return f.ImpactAssessed && f.Impact >= limit
}

// HotPaths lists hot files (see IsHot), collapsing a directory into one
// entry when it has at least two scored files and all of them are hot. The
// highest such directory wins; the repo root is never collapsed.
func HotPaths(hm *types.Heatmap, minTier types.Tier, th types.TierThresholds) []Entry {
	groups := collapse(hm, func(f *types.FileHeat) bool { return IsHot(f, minTier, th) })
	entries := make([]Entry, 0, len(groups))
	for key, files := range groups {
		e := Entry{Path: key, IsDir: strings.HasSuffix(key, "/"), Files: files}
		for i, p := range files {
			f := hm.Files[p]
			if i == 0 || f.HeatScore > e.HeatScore {
				e.HeatScore = f.HeatScore
			}
			if i == 0 || tierRank[f.Tier] > tierRank[e.Tier] {
				e.Tier = f.Tier
			}
		}
		entries = append(entries, e)
	}
	sort.Slice(entries, func(i, j int) bool {
		if entries[i].HeatScore != entries[j].HeatScore {
			return entries[i].HeatScore > entries[j].HeatScore
		}
		return entries[i].Path < entries[j].Path
	})
	return entries
}

// collapse groups the files for which in is true under one key each: the
// file's path, or "dir/" for the highest directory (never the repo root)
// with at least two scored files beneath it, all of them in.
func collapse(hm *types.Heatmap, in func(*types.FileHeat) bool) map[string][]string {
	// For every ancestor dir: total scored files and member files beneath it.
	total, members := map[string]int{}, map[string]int{}
	var memberFiles []string
	for p, f := range hm.Files {
		isMember := in(f)
		if isMember {
			memberFiles = append(memberFiles, p)
		}
		for d := path.Dir(p); d != "." && d != "/"; d = path.Dir(d) {
			total[d]++
			if isMember {
				members[d]++
			}
		}
	}
	groups := map[string][]string{}
	for _, p := range memberFiles {
		key := p
		for d := path.Dir(p); d != "." && d != "/"; d = path.Dir(d) {
			if total[d] >= 2 && members[d] == total[d] {
				key = d + "/" // keep walking up: the highest fully member dir wins
			}
		}
		groups[key] = append(groups[key], p)
	}
	for _, files := range groups {
		sort.Strings(files)
	}
	return groups
}

// CodeownersRow is one generated CODEOWNERS rule.
type CodeownersRow struct {
	Entry
	Owners []string `json:"owners"`
}

// Codeowners renders a marked CODEOWNERS block. Owners of a directory entry are
// ranked by their summed share across its files; at most maxOwners are kept.
// Entries without owners become comments so they never clear an earlier rule.
// Paths CODEOWNERS cannot express (see unrepresentableReason) also become
// comments and are returned in unrepresentable instead of rows.
func Codeowners(entries []Entry, owners map[string][]ownership.Owner, maxOwners int) (block string, rows []CodeownersRow, unrepresentable []string) {
	var b strings.Builder
	b.WriteString(BeginMarker + "\n")
	b.WriteString("# High-stakes paths and their most active recent authors.\n")
	rows = make([]CodeownersRow, 0, len(entries))
	unrepresentable = []string{}
	for _, e := range entries {
		if reason := unrepresentableReason(e.Path); reason != "" {
			fmt.Fprintf(&b, "# cannot express in CODEOWNERS (%s): %s\n", reason, e.Path)
			unrepresentable = append(unrepresentable, e.Path)
			continue
		}
		score := map[string]float64{}
		for _, f := range e.Files {
			for _, o := range owners[f] {
				score[o.Handle] += o.Share
			}
		}
		handles := make([]string, 0, len(score))
		for h := range score {
			if h != "" {
				handles = append(handles, h)
			}
		}
		sort.Slice(handles, func(i, j int) bool {
			if score[handles[i]] != score[handles[j]] {
				return score[handles[i]] > score[handles[j]]
			}
			return handles[i] < handles[j]
		})
		if len(handles) > maxOwners {
			handles = handles[:maxOwners]
		}
		rows = append(rows, CodeownersRow{Entry: e, Owners: handles})

		line := "/" + e.Path
		if len(handles) == 0 {
			fmt.Fprintf(&b, "# %s (%s, heat %d): no owner found in git history\n", line, e.Tier, e.HeatScore)
			continue
		}
		fmt.Fprintf(&b, "%s %s\n", line, strings.Join(handles, " "))
	}
	b.WriteString(EndMarker + "\n")
	return b.String(), rows, unrepresentable
}

// unrepresentableReason says why a path cannot be a CODEOWNERS rule, or "" if
// it can. GitHub documents no backslash escaping (it lists escaping a leading
// # and [ ] ranges as unsupported), so whitespace would split the path from
// its owners and a glob character would match other files. Every rule starts
// with "/", so # and ! are never leading and stay literal.
func unrepresentableReason(p string) string {
	switch {
	case strings.ContainsAny(p, " \t"):
		return "space in path"
	case strings.ContainsAny(p, `*?[]\`):
		return "glob character in path"
	}
	return ""
}

// ReplaceBlock swaps the marked block in existing CODEOWNERS content, or
// appends it. Appending puts it last, where CODEOWNERS rules take precedence.
func ReplaceBlock(existing, block string) string {
	start := strings.Index(existing, BeginMarker)
	if start >= 0 {
		if rel := strings.Index(existing[start:], EndMarker); rel >= 0 {
			end := start + rel + len(EndMarker)
			if end < len(existing) && existing[end] == '\n' {
				end++
			}
			return existing[:start] + block + existing[end:]
		}
	}
	if existing == "" {
		return block
	}
	if !strings.HasSuffix(existing, "\n") {
		existing += "\n"
	}
	return existing + "\n" + block
}

// Policy is a machine-readable no-auto-approve list for AI reviewers.
type Policy struct {
	Version     int          `json:"version" yaml:"version"`
	GeneratedBy string       `json:"generated_by" yaml:"generated_by"`
	MinTier     types.Tier   `json:"min_tier" yaml:"min_tier"`
	Description string       `json:"description" yaml:"description"`
	Paths       []string     `json:"paths" yaml:"paths"` // globs: "dir/**" or exact files
	Files       []PolicyFile `json:"files" yaml:"files"`
}

// PolicyFile explains why one file is on the list.
type PolicyFile struct {
	Path      string     `json:"path" yaml:"path"`
	Tier      types.Tier `json:"tier" yaml:"tier"`
	HeatScore int        `json:"heat_score" yaml:"heat_score"`
	Reason    string     `json:"reason,omitempty" yaml:"reason,omitempty"`
}

// Build creates the policy from hot path entries.
func Build(hm *types.Heatmap, entries []Entry, minTier types.Tier) Policy {
	p := Policy{
		Version:     1,
		GeneratedBy: "highstakes",
		MinTier:     minTier,
		Description: "Changes touching these paths must not be auto-approved by a bot; require human review.",
		Paths:       []string{},
		Files:       []PolicyFile{},
	}
	for _, e := range entries {
		if e.IsDir {
			p.Paths = append(p.Paths, e.Path+"**")
		} else {
			p.Paths = append(p.Paths, e.Path)
		}
		for _, f := range e.Files {
			fh := hm.Files[f]
			if fh == nil {
				continue
			}
			reason := fh.Factors.BlastRadius.CriticalReason
			if reason == "" {
				reason = fh.Factors.BlastRadius.Summary
			}
			p.Files = append(p.Files, PolicyFile{Path: f, Tier: fh.Tier, HeatScore: fh.HeatScore, Reason: reason})
		}
	}
	sort.SliceStable(p.Files, func(i, j int) bool {
		if p.Files[i].HeatScore != p.Files[j].HeatScore {
			return p.Files[i].HeatScore > p.Files[j].HeatScore
		}
		return p.Files[i].Path < p.Files[j].Path
	})
	return p
}

// AgentPolicy tells AI agents how far they may act on each path
// (`create policy --agents`).
type AgentPolicy struct {
	Version      int          `json:"version" yaml:"version"`
	GeneratedBy  string       `json:"generated_by" yaml:"generated_by"`
	HowToRead    string       `json:"how_to_read" yaml:"how_to_read"`
	CapRule      string       `json:"cap_rule" yaml:"cap_rule"`
	MaxLevel     int          `json:"max_level" yaml:"max_level"`
	DefaultLevel int          `json:"default_level" yaml:"default_level"` // paths no glob matches
	Levels       []AgentLevel `json:"levels" yaml:"levels"`
}

// AgentLevel is one autonomy level and the path globs at it.
type AgentLevel struct {
	types.AutonomyLevel `yaml:",inline"`
	Paths               []string `json:"paths" yaml:"paths"` // "dir/**" or exact files
}

// Agents builds the autonomy policy: every scored file at its level
// (scorer.FileAutonomy with maxLevel). At L0 and L1 directories collapse to
// "dir/**" when all their scored files share the level (globs never
// overlap); L2 and L3 list exact files, so an unassessed file added later
// falls to default_level instead of matching an elevated glob.
func Agents(hm *types.Heatmap, maxLevel int) AgentPolicy {
	p := AgentPolicy{
		Version:     1,
		GeneratedBy: "highstakes",
		HowToRead: "Match each file a change touches against the paths (dir/** covers everything under dir; paths do not overlap). " +
			"Levels 2 and 3 list exact files only, so a new file never inherits them; only levels 0 and 1 use dir/**. " +
			"The change may go as far as the lowest level among its files; a path not listed counts as default_level, " +
			"1 (propose only) unless max_level is 0. " +
			"Regenerate after analyze: levels follow the heatmap.",
		CapRule: "Levels follow the file's posture: Routine 3, Stabilize 2, Protect 1, Harden now 0. " +
			"How bad if it breaks? is AI-assessed and not human-validated, so levels are conservative: a file whose impact is not LLM-assessed is capped at 1, " +
			"and autonomy.max_level in .heatmap/config.yaml (default 3) caps every file.",
		MaxLevel:     maxLevel,
		DefaultLevel: min(1, maxLevel),
	}
	for _, l := range types.AutonomyLevels {
		level := l.Level
		groups := collapse(hm, func(f *types.FileHeat) bool { return scorer.FileAutonomy(f, maxLevel).Level == level })
		paths := make([]string, 0, len(groups))
		for key, files := range groups {
			switch {
			case level >= 2:
				paths = append(paths, files...)
			case strings.HasSuffix(key, "/"):
				paths = append(paths, key+"**")
			default:
				paths = append(paths, key)
			}
		}
		sort.Strings(paths)
		p.Levels = append(p.Levels, AgentLevel{AutonomyLevel: l, Paths: paths})
	}
	return p
}
